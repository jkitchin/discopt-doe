@dataclass(frozen=True)
class BlockedFactorialDesign:
    """A 2-level full factorial run in blocks.

    Attributes
    ----------
    factors, low, high : tuple
        Factor names and their two levels, as in :class:`FactorialDesign`.
    n_blocks : int
        Blocks per replicate.
    generators : tuple of tuple of str
        The block generators used in each replicate (``"A:B:C"`` form).
    confounded_effects : tuple of tuple of str
        For each replicate, every interaction confounded with blocks: the
        generators and all their products. With ``partial_confounding`` these
        differ between replicates.
    rows : list of dict
        One dict per run: the factor values, ``block`` (1-based and unique
        across replicates, since blocks in different replicates are different
        physical batches), ``replicate`` (0-based), ``is_center``, and
        ``run_order`` (blocks in sequence, runs randomized within each block).
    """

    factors: tuple[str, ...]
    low: tuple[object, ...]
    high: tuple[object, ...]
    n_blocks: int
    generators: tuple[tuple[str, ...], ...]
    confounded_effects: tuple[tuple[str, ...], ...]
    rows: list[dict[str, object]]

    def __len__(self) -> int:
        return len(self.rows)


def blocked_factorial_design(
    factors: Mapping[str, tuple[object, object]],
    *,
    n_blocks: int,
    block_generators: Sequence[Any] | Sequence[Sequence[Any]] | None = None,
    replicates: int = 1,
    partial_confounding: bool = False,
    center_points_per_block: int = 0,
    seed: int | None = None,
) -> BlockedFactorialDesign:
    """Split a randomized 2-level full factorial into blocks.

    Parameters
    ----------
    factors : mapping name -> (low, high)
        Two levels per factor, numeric or categorical (2 -- 8 factors).
    n_blocks : int
        Blocks per replicate: a power of two, at most ``2**(k-1)``.
    block_generators : sequence, optional
        ``log2(n_blocks)`` independent interactions to confound with blocks,
        each as a tuple of factor names, ``"A:B:C"``, or ``"ABC"`` when every
        name is a single letter. Their products are confounded too. Omit to
        use a minimum-aberration choice (automatic for up to 8 blocks). With
        ``partial_confounding=True`` pass one such sequence per replicate.
    replicates : int, default 1
        Replicates of the whole blocked design; each gets its own blocks.
    partial_confounding : bool, default False
        Confound different interactions in different replicates, so that every
        interaction is unconfounded in at least one replicate (needs
        ``replicates >= 2``). Chosen greedily: each replicate takes the
        minimum-aberration generators that overlap least with what earlier
        replicates already confounded.
    center_points_per_block : int, default 0
        Centre runs added to every block (numeric factors only). They give a
        pure-error estimate and a curvature check within each block.
    seed : int, optional
        Reproducible randomization.

    Returns
    -------
    BlockedFactorialDesign
    """
    if not factors:
        raise ValueError("at least one factor required")
    names = tuple(factors.keys())
    k = len(names)
    if k < 2 or k > 8:
        raise ValueError(f"blocked factorials support 2 -- 8 factors, got {k}")
    if replicates < 1:
        raise ValueError(f"replicates must be >= 1, got {replicates}")
    if center_points_per_block < 0:
        raise ValueError("center_points_per_block must be >= 0")
    p = int(round(np.log2(n_blocks))) if n_blocks >= 1 else -1
    if n_blocks < 2 or 2**p != n_blocks:
        raise ValueError(f"n_blocks must be a power of two >= 2, got {n_blocks}")
    if p > k - 1:
        raise ValueError(f"{k} factors allow at most {2 ** (k - 1)} blocks, got {n_blocks}")
    if partial_confounding and replicates < 2:
        raise ValueError("partial_confounding needs replicates >= 2")

    lows = tuple(factors[n][0] for n in names)
    highs = tuple(factors[n][1] for n in names)
    for n, lo, hi in zip(names, lows, highs):
        if lo == hi:
            raise ValueError(f"factor {n!r}: low and high levels must differ")
    numeric = all(_is_numeric(v) for v in lows + highs)
    if center_points_per_block and not numeric:
        raise ValueError("center_points_per_block > 0 requires all factors to be numeric")

    # Generators per replicate, as bitmasks.
    per_rep: list[list[int]] = []
    if block_generators is not None:
        if partial_confounding:
            sets = list(block_generators)
            if len(sets) != replicates:
                raise ValueError(
                    "with partial_confounding, pass one generator set per replicate "
                    f"({replicates}), got {len(sets)}"
                )
        else:
            sets = [block_generators] * replicates
        for gens in sets:
            masks = [_parse_word(g, names) for g in gens]
            if len(masks) != p:
                raise ValueError(
                    f"{n_blocks} blocks need {p} independent generators, got {len(masks)}"
                )
            span = _span(masks)
            if len(span) != 2**p - 1:
                raise ValueError("block generators are not independent")
            mains = [_word_name(w, names) for w in span if bin(w).count("1") == 1]
            if mains:
                raise ValueError(
                    f"these generators confound main effect(s) {mains} with blocks; "
                    "choose higher-order interactions"
                )
            per_rep.append(masks)
    else:
        cands = _candidate_subgroups(k, p)
        order = _aberration_order(cands, k)
        cands = cands[order]
        confounded_so_far: set[int] = set()
        for _ in range(replicates):
            if partial_confounding and confounded_so_far:
                overlap = np.isin(cands, list(confounded_so_far)).sum(axis=1)
                idx = int(np.argmin(overlap))  # stable: best aberration among least overlap
            else:
                idx = 0
            chosen = [int(w) for w in cands[idx]]
            per_rep.append(_basis(chosen, p))
            confounded_so_far |= set(chosen)
            if not partial_confounding:
                per_rep = per_rep * replicates
                break

    rng = random.Random(seed)
    rows: list[dict[str, object]] = []
    corners = list(itertools.product((0, 1), repeat=k))
    block_offset = 0
    for r, gens in enumerate(per_rep):
        blocks: dict[int, list[dict[str, object]]] = {b: [] for b in range(n_blocks)}
        for code in corners:
            b = 0
            for j, g in enumerate(gens):
                sign = 1
                for i in range(k):
                    if g >> i & 1 and not code[i]:
                        sign = -sign
                if sign > 0:
                    b |= 1 << j
            row: dict[str, object] = {names[i]: highs[i] if code[i] else lows[i] for i in range(k)}
            row["is_center"] = False
            blocks[b].append(row)
        for b in range(n_blocks):
            for _ in range(center_points_per_block):
                cp: dict[str, object] = {
                    names[i]: (float(cast(float, lows[i])) + float(cast(float, highs[i]))) / 2.0
                    for i in range(k)
                }
                cp["is_center"] = True
                blocks[b].append(cp)
        block_order = list(range(n_blocks))
        rng.shuffle(block_order)
        for label, b in enumerate(block_order, start=1):
            members = blocks[b]
            rng.shuffle(members)
            for row in members:
                row["block"] = block_offset + label
                row["replicate"] = r
                rows.append(row)
        block_offset += n_blocks
    for i, row in enumerate(rows):
        row["run_order"] = i

    return BlockedFactorialDesign(
        factors=names,
        low=lows,
        high=highs,
        n_blocks=n_blocks,
        generators=tuple(tuple(_word_name(g, names) for g in gens) for gens in per_rep),
        confounded_effects=tuple(
            tuple(
                _word_name(w, names)
                for w in sorted(_span(gens), key=lambda w: (bin(w).count("1"), w))
            )
            for gens in per_rep
        ),
        rows=rows,
    )


def _basis(words: Sequence[int], p: int) -> list[int]:
    """``p`` independent words spanning the given subgroup elements."""
    basis: list[int] = []
    for w in words:
        if len(basis) == p:
            break
        if not basis or w not in _span(basis):
            basis.append(w)
    return basis


def _ordered_levels(values) -> list[object]:
    """Distinct levels, numeric ones in numeric order (so the second is "high")."""
    uniq = list(dict.fromkeys(values))
    if all(_is_numeric(v) for v in uniq):
        return sorted(uniq, key=lambda v: float(cast(float, v)))
    return sorted(uniq, key=str)


def _is_numeric(v: object) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


