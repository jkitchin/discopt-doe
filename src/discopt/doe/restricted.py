"""Restricted randomization: blocked factorials and split-plot designs.

Two situations stop you from running a factorial in one completely random
order, and each needs its own design *and* its own analysis.

Blocking
--------

The runs do not fit in one homogeneous batch: two days, four raw-material
lots, eight furnace loads. :func:`blocked_factorial_design` splits a 2-level
full factorial into ``n_blocks`` blocks by *confounding* chosen interactions
with blocks: every run in a block has the same sign on each block generator,
so the block effect is estimated and removed at the cost of those
interactions. The default generators are chosen by a minimum-aberration search
(confound the highest-order interactions possible, never a main effect), and
``partial_confounding=True`` confounds a *different* interaction in each
replicate so that every interaction is estimable from some replicate.

Analyse with :func:`discopt.doe.anova_report`, passing the ``block`` column as
a factor and leaving the confounded interactions out of the model (they are
aliased with blocks, and ``anova_report`` refuses them).

Split-plot
----------

Some factors are hard to change (a furnace temperature, a reactor charge), so
they are set once per *whole plot* while the easy-to-change factors vary
within it. :func:`split_plot_design` builds that two-layer randomization, and
:func:`split_plot_anova` gives each effect the error term that matches the unit
it was applied to: whole-plot factors are tested against the variation between
whole plots, and sub-plot factors (and their interactions with whole-plot
factors) against the variation within them. Analysing a split-plot as if it
were completely randomized pools the two errors, so whole-plot effects look far
more significant than they are, and sub-plot effects less.

The analysis is the classical stratum decomposition for balanced data, whose
variance-component estimates coincide with REML when both are positive.
"""

from __future__ import annotations

import itertools
