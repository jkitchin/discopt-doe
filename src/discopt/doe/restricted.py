@dataclass
class SplitPlotAnovaTable:
    """Two-stratum ANOVA for a balanced split-plot experiment.

    Attributes
    ----------
    rows : list of AnovaEffect
        Whole-plot terms, ``"Whole-plot error"``, sub-plot terms,
        ``"Sub-plot error"``, and ``"Total"``, in that order. Each term's F and
        p are computed against its own stratum's error.
    strata : dict
        ``term -> "whole-plot"`` or ``"sub-plot"``.
    variance_components : dict
        ``{"whole_plot": σ²_WP, "sub_plot": σ²_SP}``: the ANOVA (method-of-
        moments) estimates, equal to REML for balanced data when positive;
        a negative whole-plot estimate is truncated at 0.
    effects : list of dict
        For every term whose factors all have two levels: the signed effect
        (mean at the product-sign +1 minus mean at -1), its standard error
        from the matching stratum, degrees of freedom, t and p.
    n_obs, n_whole_plots, runs_per_whole_plot : int
    response : str
    """

    rows: list[AnovaEffect]
    strata: dict[str, str]
    variance_components: dict[str, float]
    effects: list[dict[str, Any]] = field(default_factory=list)
    n_obs: int = 0
    n_whole_plots: int = 0
    runs_per_whole_plot: int = 0
    response: str = ""

    def summary(self) -> str:
        header = f"{'Source':<22s} {'SS':>12s} {'df':>5s} {'MS':>12s} {'F':>9s} {'p':>10s}"
        lines = [header, "-" * len(header)]
        for r in self.rows:
            f_str = "      ---" if r.f is None else f"{r.f:9.3f}"
            p_str = "       ---" if r.p is None else f"{r.p:10.4g}"
            ms_str = "         ---" if r.source == "Total" or r.df == 0 else f"{r.ms:12.4f}"
            lines.append(f"{r.source:<22s} {r.ss:12.4f} {r.df:5d} {ms_str} {f_str} {p_str}")
        vc = self.variance_components
        lines.append("")
        lines.append(
            f"Variance components: whole-plot {vc['whole_plot']:.4g}, sub-plot {vc['sub_plot']:.4g}"
        )
        return "\n".join(lines)

    def __str__(self) -> str:
        return self.summary()


def _term_block(rows: Sequence[Mapping[str, object]], term: tuple[str, ...]) -> np.ndarray:
    keys = [tuple(r[f] for f in term) for r in rows]
    cells: dict[tuple[object, ...], int] = {}
    for key in keys:
        cells.setdefault(key, len(cells))
    block = np.zeros((len(rows), len(cells)))
    for i, key in enumerate(keys):
        block[i, cells[key]] = 1.0
    return block


def _sequential(
    rows: Sequence[Mapping[str, object]],
    y: np.ndarray,
    base: np.ndarray,
    terms: Sequence[tuple[str, ...]],
    levels: Mapping[str, list[object]],
) -> tuple[list[tuple[str, float, int]], float, int]:
    """Sequential SS for ``terms`` after the columns in ``base``."""
    X = base
    rank = int(np.linalg.matrix_rank(X))
    coef, *_ = np.linalg.lstsq(X, y, rcond=None)
    rss = float(np.sum((y - X @ coef) ** 2))
    out = []
    for term in terms:
        nominal = 1
        for f in term:
            nominal *= len(levels[f]) - 1
        X_new = np.hstack([X, _term_block(rows, term)])
        rank_new = int(np.linalg.matrix_rank(X_new))
        df = rank_new - rank
        if df < nominal:
            raise ValueError(
                f"term {':'.join(term)!r} is aliased: {nominal} degrees of freedom but only "
                f"{df} are estimable after the terms before it"
            )
        coef, *_ = np.linalg.lstsq(X_new, y, rcond=None)
        rss_new = float(np.sum((y - X_new @ coef) ** 2))
        out.append((":".join(term), max(rss - rss_new, 0.0), df))
        X, rank, rss = X_new, rank_new, rss_new
    return out, rss, rank


def split_plot_anova(
    rows: Sequence[Mapping[str, object]],
    response: str,
    *,
    whole_plot_factors: Sequence[str],
    sub_plot_factors: Sequence[str],
    whole_plot: str = "whole_plot",
    interactions: Sequence[Sequence[str]] | None = None,
) -> SplitPlotAnovaTable:
    """Analyse a balanced split-plot experiment with two error strata.

    Whole-plot terms (main effects of whole-plot factors, and interactions
    among them only) are tested against **whole-plot error**: the variation of
    whole-plot means about the whole-plot model. Everything else (sub-plot main
    effects and any interaction involving a sub-plot factor) is tested against
    **sub-plot error**: the residual within whole plots, with every whole plot
    as a block. Sums of squares are sequential within each stratum, in the
    order main effects, then ``interactions``.

    Parameters
    ----------
    rows : sequence of mapping
        One row per run, with the response, every factor, and the whole-plot id.
    response : str
        The response column.
    whole_plot_factors, sub_plot_factors : sequence of str
        Hard-to-change and easy-to-change factors.
    whole_plot : str, default ``"whole_plot"``
        Column identifying the whole plot each run belongs to.
    interactions : sequence of tuple of str, optional
        Interaction terms to include. Each is assigned to its stratum
        automatically.

    Returns
    -------
    SplitPlotAnovaTable

    Raises
    ------
    ValueError
        If a column is missing, a whole-plot factor varies within a whole plot,
        whole plots are unequal in size, or a term is aliased.
    """
    from scipy.stats import f as f_dist
    from scipy.stats import t as t_dist

    rows = list(rows)
    wp_f, sp_f = list(whole_plot_factors), list(sub_plot_factors)
    if not wp_f or not sp_f:
        raise ValueError("need at least one whole-plot and one sub-plot factor")
    needed = [response, whole_plot, *wp_f, *sp_f]
    missing = sorted({c for c in needed for r in rows if c not in r})
    if missing:
        raise ValueError(f"column(s) {missing} missing from some rows")
    try:
        y = np.array([float(cast(float, r[response])) for r in rows])
    except (TypeError, ValueError) as e:
        raise ValueError(f"response column {response!r} must be numeric") from e
    if not np.all(np.isfinite(y)):
        raise ValueError("response contains non-finite values")

    # Whole-plot bookkeeping and balance.
    plots: dict[object, list[int]] = {}
    for i, r in enumerate(rows):
        plots.setdefault(r[whole_plot], []).append(i)
    sizes = {len(v) for v in plots.values()}
    if len(sizes) != 1:
        raise ValueError(
            f"whole plots have unequal sizes {sorted(sizes)}; the design must be balanced"
        )
    m = sizes.pop()
    if m < 2:
        raise ValueError("each whole plot needs at least two runs")
    for f in wp_f:
        for w, idx in plots.items():
            if len({rows[i][f] for i in idx}) != 1:
                raise ValueError(
                    f"whole-plot factor {f!r} varies within whole plot {w!r}; it must be "
                    "constant within each whole plot"
                )

    levels = {f: _ordered_levels(r[f] for r in rows) for f in wp_f + sp_f}
    wp_terms: list[tuple[str, ...]] = [(f,) for f in wp_f]
    sp_terms: list[tuple[str, ...]] = [(f,) for f in sp_f]
    for inter in interactions or ():
        term = tuple(inter)
        unknown = [f for f in term if f not in levels]
        if unknown:
            raise ValueError(f"interaction {term}: unknown factor(s) {unknown}")
        (wp_terms if all(f in wp_f for f in term) else sp_terms).append(term)

    n, n_wp = len(rows), len(plots)
    grand = float(y.mean())
    ss_total = float(np.sum((y - grand) ** 2))

    # Whole-plot stratum: the whole-plot means, scaled back by m.
    plot_ids = list(plots)
    wp_rows = [rows[plots[w][0]] for w in plot_ids]
    wp_means = np.array([y[plots[w]].mean() for w in plot_ids])
    wp_results, wp_rss, wp_rank = _sequential(
        wp_rows, wp_means, np.ones((n_wp, 1)), wp_terms, levels
    )
    wp_results = [(name, m * ss, df) for name, ss, df in wp_results]
    ss_wp_err = m * wp_rss
    df_wp_err = n_wp - wp_rank

    # Sub-plot stratum: whole plots as blocks.
    plot_block = _term_block(rows, (whole_plot,))
    sp_results, sp_rss, sp_rank = _sequential(rows, y, plot_block, sp_terms, levels)
    df_sp_err = n - sp_rank
    if df_sp_err < 1:
        raise ValueError("no degrees of freedom left for sub-plot error; drop a term")

    ms_wp_err = ss_wp_err / df_wp_err if df_wp_err > 0 else float("nan")
    ms_sp_err = sp_rss / df_sp_err
    if df_wp_err == 0:
        warnings.warn(
            "no degrees of freedom for whole-plot error (one whole plot per "
            "whole-plot treatment): whole-plot factors cannot be tested",
            stacklevel=2,
        )

    def tested(name: str, ss: float, df: int, ms_err: float, df_err: int) -> AnovaEffect:
        ms = ss / df
        if df_err > 0 and ms_err > 0:
            f_stat = ms / ms_err
            return AnovaEffect(name, ss, df, ms, f_stat, float(f_dist.sf(f_stat, df, df_err)))
        return AnovaEffect(name, ss, df, ms, None, None)

    out_rows = [tested(nm, ss, df, ms_wp_err, df_wp_err) for nm, ss, df in wp_results]
    out_rows.append(AnovaEffect("Whole-plot error", ss_wp_err, df_wp_err, ms_wp_err, None, None))
    out_rows += [tested(nm, ss, df, ms_sp_err, df_sp_err) for nm, ss, df in sp_results]
    out_rows.append(AnovaEffect("Sub-plot error", sp_rss, df_sp_err, ms_sp_err, None, None))
    out_rows.append(AnovaEffect("Total", ss_total, n - 1, 0.0, None, None))

    strata = {nm: "whole-plot" for nm, _, _ in wp_results}
    strata.update({nm: "sub-plot" for nm, _, _ in sp_results})

    sigma2_wp = (ms_wp_err - ms_sp_err) / m if df_wp_err > 0 else float("nan")
    variance_components = {
        "whole_plot": max(sigma2_wp, 0.0) if np.isfinite(sigma2_wp) else float("nan"),
        "sub_plot": ms_sp_err,
    }

    # Signed effects for 2-level terms, each with its own stratum's error.
    effects = []
    for term in wp_terms + sp_terms:
        if not all(len(levels[f]) == 2 for f in term):
            continue
        sign = np.ones(n)
        for f in term:
            hi = levels[f][1]
            sign *= np.array([1.0 if r[f] == hi else -1.0 for r in rows])
        if np.sum(sign > 0) == 0 or np.sum(sign < 0) == 0:
            continue
        effect = float(y[sign > 0].mean() - y[sign < 0].mean())
        name = ":".join(term)
        stratum = strata[name]
        ms_err, df_err = (
            (ms_wp_err, df_wp_err) if stratum == "whole-plot" else (ms_sp_err, df_sp_err)
        )
        se = float(np.sqrt(4.0 * ms_err / n)) if df_err > 0 else float("nan")
        t_val = effect / se if se and np.isfinite(se) and se > 0 else float("nan")
        p_val = float(2 * t_dist.sf(abs(t_val), df_err)) if np.isfinite(t_val) else float("nan")
        effects.append(
            {
                "term": name,
                "stratum": stratum,
                "effect": effect,
                "se": se,
                "df": df_err,
                "t": t_val,
                "p": p_val,
                "high": tuple(levels[f][1] for f in term),
            }
        )

    return SplitPlotAnovaTable(
        rows=out_rows,
        strata=strata,
        variance_components=variance_components,
        effects=effects,
        n_obs=n,
        n_whole_plots=n_wp,
        runs_per_whole_plot=m,
        response=response,
    )
