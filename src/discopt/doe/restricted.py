@dataclass(frozen=True)
class SplitPlotDesign:
    """A randomized split-plot design.

    Attributes
    ----------
    whole_plot_factors, sub_plot_factors : tuple of str
        Hard-to-change factors (set once per whole plot) and easy-to-change
        factors (varied within each whole plot).
    levels : dict
        ``name -> (low, high)`` for every factor.
    n_whole_plots : int
        Number of whole plots (e.g. furnace runs).
    rows : list of dict
        One dict per run: every factor value, ``whole_plot`` (0-based, in run
        sequence), ``replicate`` (which copy of the *whole-plot* factorial this
        whole plot belongs to; not a block of the whole experiment),
        ``sub_replicate`` (which copy of the sub-plot factorial within the
        whole plot), and ``run_order``. Whole plots run in random order, and
        the sub-plot runs are randomized *within* each whole plot.
    """

    whole_plot_factors: tuple[str, ...]
    sub_plot_factors: tuple[str, ...]
    levels: dict[str, tuple[object, object]]
    n_whole_plots: int
    rows: list[dict[str, object]]

    def __len__(self) -> int:
        return len(self.rows)


def split_plot_design(
    whole_plot_factors: Mapping[str, tuple[object, object]],
    sub_plot_factors: Mapping[str, tuple[object, object]],
    *,
    whole_plot_replicates: int = 2,
    sub_plot_replicates: int = 1,
    seed: int | None = None,
) -> SplitPlotDesign:
    """Build a 2-level split-plot design.

    Every combination of the whole-plot factors is run ``whole_plot_replicates``
    times as a whole plot, and each whole plot holds the full factorial in the
    sub-plot factors ``sub_plot_replicates`` times (e.g. 16 samples in one
    furnace firing for a 2^3 sub-plot factorial run twice).

    Parameters
    ----------
    whole_plot_factors : mapping name -> (low, high)
        Hard-to-change factors. Levels may be numeric or categorical.
    sub_plot_factors : mapping name -> (low, high)
        Easy-to-change factors.
    whole_plot_replicates : int, default 2
        Whole plots per whole-plot treatment. At least 2: with one, there are
        no degrees of freedom for whole-plot error, and the whole-plot factors
        cannot be tested at all.
    sub_plot_replicates : int, default 1
        Copies of the sub-plot factorial inside each whole plot. Extra copies
        add sub-plot error degrees of freedom; they do nothing for the
        whole-plot factors, whose precision is set by the number of whole plots.
    seed : int, optional
        Reproducible randomization.
    """
    if not whole_plot_factors or not sub_plot_factors:
        raise ValueError("a split-plot needs at least one whole-plot and one sub-plot factor")
    overlap = set(whole_plot_factors) & set(sub_plot_factors)
    if overlap:
        raise ValueError(f"factors cannot be both whole-plot and sub-plot: {sorted(overlap)}")
    if whole_plot_replicates < 1:
        raise ValueError("whole_plot_replicates must be >= 1")
    if sub_plot_replicates < 1:
        raise ValueError("sub_plot_replicates must be >= 1")
    if whole_plot_replicates == 1:
        warnings.warn(
            "whole_plot_replicates=1 leaves no degrees of freedom for whole-plot "
            "error: the whole-plot factors cannot be tested",
            stacklevel=2,
        )
    levels: dict[str, tuple[object, object]] = {}
    for name, (lo, hi) in {**whole_plot_factors, **sub_plot_factors}.items():
        if lo == hi:
            raise ValueError(f"factor {name!r}: low and high levels must differ")
        levels[name] = (lo, hi)

    wp_names = tuple(whole_plot_factors)
    sp_names = tuple(sub_plot_factors)
    rng = random.Random(seed)
    whole_plots: list[dict[str, object]] = []
    for r in range(whole_plot_replicates):
        for code in itertools.product((0, 1), repeat=len(wp_names)):
            wp = {n: levels[n][c] for n, c in zip(wp_names, code)}
            wp["replicate"] = r
            whole_plots.append(wp)
    rng.shuffle(whole_plots)

    rows: list[dict[str, object]] = []
    for w, wp in enumerate(whole_plots):
        subs = [
            {**{n: levels[n][c] for n, c in zip(sp_names, code)}, "sub_replicate": s_rep}
            for s_rep in range(sub_plot_replicates)
            for code in itertools.product((0, 1), repeat=len(sp_names))
        ]
        rng.shuffle(subs)
        for sp in subs:
            rows.append(
                {
                    **{n: wp[n] for n in wp_names},
                    **sp,
                    "whole_plot": w,
                    "replicate": wp["replicate"],
                }
            )
    for i, row in enumerate(rows):
        row["run_order"] = i

    return SplitPlotDesign(
        whole_plot_factors=wp_names,
        sub_plot_factors=sp_names,
        levels=levels,
        n_whole_plots=len(whole_plots),
        rows=rows,
    )


